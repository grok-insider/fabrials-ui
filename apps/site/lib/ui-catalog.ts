function ui(
  slug: string,
  title: string,
  group: UiGroup,
  description: string,
  exports: string[],
  props: UiCatalogItem["props"],
  note: string,
  pkg: UiPackage = "@fabrials/ui",
  /** What a page with nothing to import shows under Installation (a CSS page, a page of tokens). */
  setup?: string,
): UiCatalogItem {
  const importLine =
    pkg === "@fabrials/ai-ui"
      ? `import { ${exports.join(", ")} } from "${pkg}";\nimport "@fabrials/ai-ui/styles.css";`
      : `import { ${exports.join(", ")} } from "${pkg}";`;
  return {
    slug,
    title,
    group,
    description,
    exports,
    props,
    note,
    usage: setup ?? (exports.length > 0 ? importLine : `@import "${pkg}/styles.css";`),
    package: pkg,
  };
}

function aiUi(
  slug: string,
  title: string,
  description: string,
  exports: string[],
  props: UiCatalogItem["props"],
  note: string,
): UiCatalogItem {
  return ui(slug, title, "AI", description, exports, props, note, "@fabrials/ai-ui");
}

